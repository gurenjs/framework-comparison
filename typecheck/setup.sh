#!/usr/bin/env bash
# Prepares the four projects the typecheck benchmark generates routes into.
# Everything lands in typecheck/.work/ (gitignored). Versions are pinned so a
# re-run measures the same compiler and libraries.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p .work
cd .work

TS=7.0.2
ZOD=4.6.7

# Guren: the published create-guren-app default blueprint, as a user gets it.
if [ ! -d guren ]; then
  bunx create-guren-app@1.18.4 guren --blueprint default --db sqlite --agents none --no-git </dev/null
  # The template's own dependency ranges float; pin what TYPECHECK.md measured.
  (cd guren \
    && bun add --exact @guren/core@1.24.0 @guren/cli@2.31.1 @guren/inertia-client@1.2.2 @guren/orm@2.14.0 \
      @inertiajs/react@3.9.1 react@19.3.1 react-dom@19.3.1 zod@$ZOD \
    && bun add -d --exact typescript@$TS @types/react@19.3.0)
fi

# Void: routes/ + .void/ generated by `void prepare`, typed fetch from void/client.
if [ ! -d void ]; then
  mkdir void
  cat > void/package.json <<EOF
{ "name": "tc-void", "private": true, "type": "module",
  "dependencies": { "void": "1.1.11", "zod": "$ZOD" },
  "devDependencies": { "typescript": "$TS" } }
EOF
  cat > void/tsconfig.json <<'EOF'
{
  "extends": "./.void/tsconfig.json",
  "compilerOptions": {
    "target": "ES2022",
    "module": "ES2022",
    "moduleResolution": "bundler",
    "strict": true,
    "skipLibCheck": true,
    "noEmit": true,
    "types": ["void/env"]
  },
  "include": ["routes", "src"]
}
EOF
  (cd void && bun install --ignore-scripts)
fi

# Hono RPC: one project, used for both the chained and the split app.
for stack in hono-chain hono-split; do
  if [ ! -d $stack ]; then
    mkdir $stack
    cat > $stack/package.json <<EOF
{ "name": "tc-$stack", "private": true, "type": "module",
  "dependencies": { "hono": "4.13.13", "@hono/zod-validator": "0.9.1", "zod": "$ZOD" },
  "devDependencies": { "typescript": "$TS" } }
EOF
    cat > $stack/tsconfig.json <<'EOF'
{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ES2022",
    "moduleResolution": "bundler",
    "strict": true,
    "skipLibCheck": true,
    "noEmit": true
  },
  "include": ["src"]
}
EOF
    (cd $stack && bun install)
  fi
done
